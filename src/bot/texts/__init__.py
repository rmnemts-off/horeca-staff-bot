"""Every user-visible string of the bot (TZ 8.2, CLAUDE.md, plan task 21).

This is the only place in `src/` where Russian literals are allowed, so that the customer
can reword messages without a developer; `tests/test_no_seed_data.py` enforces that over
the whole repository, and this package is the single exception it carves out.

**Wording only, never venue content.** Checklist lines, write-off reasons, product
categories, recipes and suppliers are entered by the venue and live in the database; the
system ships empty (principle 1.4#6, criterion 11.5). The same guard is stricter inside
this package for exactly that reason: a list of three phrases here is a checklist, not a
message, so every string is a separately named constant and the only collections are
mappings from a code-side enum to constants declared above them.

Layout, one module per functional block:

| Module | What it covers |
|---|---|
| `common` | navigation («⬅️ Назад», «🏠 В меню», «Отмена»), confirmation, shared formats |
| `errors` | TZ 8.2 and 9: the apology, the refusal, the stale screen |
| `onboarding` | TZ 5.1: `/start`, invite codes, the name and the position |
| `menu` | TZ 5.2: the captions of the main menu |
| `shifts` | TZ 5.3: «📋 Моя смена» and «📅 График» |
| `checklists` | TZ 5.4: the checklist message, finishing it, skipping lines |
| `recipes` | TZ 5.5: search, the list of hits, the card, unit labels |
| `admin` | TZ 5.8: employees, schedule, editors, venue settings, role labels |
| `notifications` | TZ 6: the body of every queued notification type |

**Naming, and why the tests care.** A caption ends in `_BUTTON` (or `_BUTTON_TEMPLATE`) and
is measured against the 20-character rule of TZ 8.2; a string with `{placeholders}` ends in
`_TEMPLATE` and one without must contain no braces. Both are checked in
`tests/bot/test_texts.py`, which reads this namespace — so a constant that never reaches it
is a constant no rule applies to, and the aggregation below is asserted to be complete.
"""

